"""DLC under continuous asynchrony (docs/ASYNC.md) on verl 8718ca30, v1 separate-async trainer
(trainer/ppo/v1/trainer_separate_async.py; scripts/train.sh SOURCE=async: parameter_sync_step=1, so the sampler gets the
trainer weights after every optimizer step; partial rollout: CheckpointEngineManager.update_weights aborts the in-flight
requests, pushes, resumes, and FullyAsyncLLMServerClient.generate resubmits prompt + tokens so far).
Pure math: tim/dlc/async_versions.py. Loaded through VERL_USE_EXTERNAL_MODULES in every process.

Per-token version k(t) (rollout processes):
  server   vLLMHttpServer._park_until_admitted / generate: the version of a segment is the server's global_steps when the
           request is ADMITTED to the engine (the gate it passes is closed by abort_all_requests before every weight push
           and reopened only after set_global_steps, so every token of the segment comes from those weights, also when the
           segment is aborted). Returned as TokenOutput.extra_fields["tim_admit_version"]. Not the global_steps verl puts
           there (read when the segment RETURNS: an aborted segment can come back after set_global_steps moved), and not
           a client-side read at submission (a request submitted while the gate is closed is generated by the NEW weights).
  client   FullyAsyncLLMServerClient.generate (resume loop) + LLMServerClient.generate (one call per segment): the
           segments' (version, token count) are collected in a ContextVar of the session's task, expanded to one version
           per generated token, extra_fields["tim_token_versions"].
  output   AgentLoopOutput.as_dict: popped from extra_fields into the TransferQueue field `rollout_token_versions`
           (response-level, int64, like rollout_log_probs).

Trainer (driver = TaskRunner process), TIM_ASYNC_OLD:
  metrics  (pg, tis: bypass mode, old_log_probs = the sampler's) version-gap histogram, then verl's own path.
  version  (dlc_async, dlc_admission, m2po) PPOTrainerSeparateAsync._compute_old_log_prob is REPLACED (it overrides
           PPOTrainer's, so the PPOTrainer patch of tim.dlc.hooks would not apply): the current weights (version cur =
           global_steps - 1) are saved to CPU (DetachActorWorker.save_model_to_cpu, FSDP2 shards; the newest
           TIM_ASYNC_KEEP versions are kept), verl's own forward gives log p_theta_t (+ entropy, debug metrics); for every
           other version in the batch: restore_model_from_cpu(k), a forward, keep the tokens of version k; then the current
           weights are restored. old_log_probs = log p_theta_k(t); tim_logp_theta_t = log p_theta_t (the M2PO
           stash). TIM_SPLIT_ENGINE=sc (dlc_async): every forward also returns log p at the sampler's top-k ids through
           the REF_FLAG head path of tim.dlc.hooks on the actor engine, merged per token into `ref_topk_log_probs` (the
           p_old of the centering term, tim.dlc.centering.split_sc_correction). Tokens whose version is not kept: their response is masked
           (response_mask = loss_mask = 0), counted in tim/async_missing_resp_frac (TIM_ASYNC_MISSING=raise stops instead).
  ESS      TIM_ASYNC_ESS_MIN (dlc_admission): per response 1/mean_t(rho_t^2), rho_t = p_theta_t / p_theta_k(t); below the
           threshold the response is masked and its prompt re-issued under a fresh uid (a whole group of n: verl generates
           a prompt's n samples together), at most TIM_ASYNC_ESS_MAX_DEFER times per original prompt. GRPO
           (core_algos.compute_grpo_outcome_advantage): the group mean still includes the masked response's reward (scores
           = token_level_rewards.sum(-1) ignores the mask), its own advantage is zeroed by the mask
           (scores.unsqueeze(-1) * response_mask, v1/utils.py broadcasts with the same mask), and the token-mean loss's
           denominator (loss_mask.sum()) drops its tokens.
  check    PPOTrainer._update_actor raises if the version-aware old-log-prob did not run in this step.

Worker processes: DetachActorWorker.save_model_to_cpu / restore_model_from_cpu reshard every FSDP2 module first (an FSDP2
root stays unsharded after a no-grad forward, tim.dlc.hooks.copy_trainer_to_ref) and restoring a missing version raises
(verl's silently does nothing).
"""
