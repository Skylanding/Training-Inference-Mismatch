ENV = "TIM_ASYNC"                      # "1": the rollout-side version capture (every async4 run)
ENV_OLD = "TIM_ASYNC_OLD"              # metrics | version
ENV_KEEP = "TIM_ASYNC_KEEP"            # CPU snapshots kept (current included), default 5 = the last 4 + current
ENV_ESS = "TIM_ASYNC_ESS_MIN"          # ESS admission threshold (dlc_admission: 0.5); unset = off
ENV_MAX_DEFER = "TIM_ASYNC_ESS_MAX_DEFER"
ENV_MISSING = "TIM_ASYNC_MISSING"      # mask (default) | raise
ADMIT_KEY = "tim_admit_version"        # TokenOutput.extra_fields of one server segment
TOKENS_KEY = "tim_token_versions"      # TokenOutput / AgentLoopOutput extra_fields: one version per generated token
FIELD = "rollout_token_versions"       # TransferQueue field (response-level)
STASH = "tim_logp_theta_t"             # tim.baselines.hooks.STASH
REF_FLAG = "tim_ref_topk"              # tim.dlc.hooks.REF_FLAG
REF_FIELD = "ref_topk_log_probs"       # tim.dlc.hooks.REF_FIELD
RAN = "async_old_step"                 # STATE key: the global step whose old-log-prob ran through this hook

_SEGMENTS = contextvars.ContextVar("tim_async_segments", default=None)


def old_mode() -> str:
    mode = os.environ.get(ENV_OLD, "") or "metrics"
    if mode not in ("metrics", "version"):
        raise ValueError(f"{ENV_OLD}={mode!r}: metrics or version")
    return mode


def ess_min():
    raw = os.environ.get(ENV_ESS, "")
    return float(raw) if raw else None


def _engine() -> str:
    return os.environ.get("TIM_SPLIT_ENGINE", "") or "none"


