def patch_server(module) -> str:
    cls = module.vLLMHttpServer
    park, gen = cls.__dict__.get("_park_until_admitted"), cls.__dict__.get("generate")
    if park is None or gen is None:
        return "not applied: vLLMHttpServer._park_until_admitted / generate are gone"
    if getattr(gen, "tim_async", False):
        return "applied"

    @functools.wraps(park)
    async def _park_until_admitted(self, request_id, *args, **kwargs):
        rejected = await park(self, request_id, *args, **kwargs)
        if rejected is None:           # admitted: the engine's weights are version self.global_steps until the next abort
            self.__dict__.setdefault("_tim_admit", {})[id(asyncio.current_task())] = self.global_steps
        return rejected

    @functools.wraps(gen)
    async def generate(self, *args, **kwargs):
        box = self.__dict__.setdefault("_tim_admit", {})
        key = id(asyncio.current_task())
        box.pop(key, None)
        try:
            out = await gen(self, *args, **kwargs)
        finally:
            version = box.pop(key, None)
        extra = getattr(out, "extra_fields", None)
        if isinstance(extra, dict):
            extra[ADMIT_KEY] = version
        return out

    generate.tim_async = True
    cls._park_until_admitted, cls.generate = _park_until_admitted, generate
    return "applied (segment version = server global_steps at admission)"


def patch_client(module) -> str:
    base, fa = module.LLMServerClient, module.FullyAsyncLLMServerClient
    inner, outer = base.__dict__.get("generate"), fa.__dict__.get("generate")
    if inner is None or outer is None:
        return "not applied: LLMServerClient / FullyAsyncLLMServerClient.generate are gone"
    if getattr(outer, "tim_async", False):
        return "applied"

    @functools.wraps(inner)
    async def segment_generate(self, *args, **kwargs):      # one server call (FullyAsync's super().generate)
        out = await inner(self, *args, **kwargs)
        segments = _SEGMENTS.get()
        if segments is not None:
            segments.append(((out.extra_fields or {}).get(ADMIT_KEY), len(out.token_ids or [])))
        return out

    @functools.wraps(outer)
    async def resume_generate(self, *args, **kwargs):       # the partial-rollout resume loop
        segments = []
        token = _SEGMENTS.set(segments)
        try:
            out = await outer(self, *args, **kwargs)
        finally:
            _SEGMENTS.reset(token)
        out.extra_fields[TOKENS_KEY] = segment_token_versions(segments, len(out.token_ids))
        return out

    segment_generate.tim_async = resume_generate.tim_async = True
    base.generate, fa.generate = segment_generate, resume_generate
    return "applied (per-token versions from the resume loop's segments)"


def patch_output(module) -> str:
    cls = module.AgentLoopOutput
    original = cls.as_dict
    if getattr(original, "tim_async", False):
        return "applied"

    def as_dict(self):
        import torch
        out = original(self)
        extra = out.get("extra_fields")
        versions = extra.pop(TOKENS_KEY, None) if isinstance(extra, dict) else None
        if versions is not None:
            n = int(out["responses"].size(0))
            versions = list(versions)[:n]
            versions += [MISSING] * (n - len(versions))       # the trainer refuses MISSING on a valid token
            out[FIELD] = torch.tensor(versions, dtype=torch.int64)
        return out

    as_dict.tim_async = True
    cls.as_dict = as_dict
    return f"applied (extra_fields[{TOKENS_KEY}] -> TransferQueue field {FIELD})"


