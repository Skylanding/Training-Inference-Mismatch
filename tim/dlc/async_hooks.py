def _reshard(module) -> None:
    from torch.distributed.fsdp import FSDPModule
    if not isinstance(module, FSDPModule):
        raise RuntimeError(f"per-version snapshots need FSDP2 (actor.strategy=fsdp2), got {type(module).__name__}")
    for m in module.modules():
        if isinstance(m, FSDPModule):
            m.reshard()


def patch_worker(module) -> str:
    cls = module.DetachActorWorker
    save, restore = cls.__dict__.get("save_model_to_cpu"), cls.__dict__.get("restore_model_from_cpu")
    if save is None or restore is None:
        return "not applied: DetachActorWorker.save_model_to_cpu / restore_model_from_cpu are gone"
    if getattr(save, "tim_async", False):
        return "applied"

    @functools.wraps(save)        # wraps copies __dict__: verl's @register dispatch attribute stays on the method
    def save_model_to_cpu(self, n):
        _reshard(self.actor.engine.module)
        return save(self, n)

    @functools.wraps(restore)
    def restore_model_from_cpu(self, n):
        if n not in getattr(self, "cpu_saved_models", {}):
            raise KeyError(f"no CPU snapshot of version {n} (kept: {sorted(getattr(self, 'cpu_saved_models', {}))})")
        _reshard(self.actor.engine.module)
        return restore(self, n)

    save_model_to_cpu.tim_async = restore_model_from_cpu.tim_async = True
    cls.save_model_to_cpu, cls.restore_model_from_cpu = save_model_to_cpu, restore_model_from_cpu
    return "applied (reshard before save / restore; restoring a missing version raises)"


