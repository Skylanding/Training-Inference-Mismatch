class _State:
    def __init__(self):
        self.kept = set()          # versions with a CPU snapshot on the actor workers
        self.prompts = {}          # ESS: uid -> (submitted prompt TensorDict, row, root uid, step)
        self.roots = {}            # ESS: uid about to be submitted as a re-issue -> its original prompt's uid
        self.defers = {}           # ESS: root uid -> times deferred
        self.reissued = {}         # ESS: new uid -> (step deferred, newest token version of the deferred responses)
        self.deferred_total = 0


def _state(trainer) -> _State:
    st = trainer.__dict__.get("_tim_async")
    if st is None:
        st = trainer.__dict__["_tim_async"] = _State()
    return st


def _uid(key: str) -> str:
    return key.split("_", 1)[0]


def _batch_versions(tq, batch):
    data = tq.kv_batch_get(keys=batch.keys, partition_id=batch.partition_id,
                           select_fields=[FIELD, "response_mask", "rollout_log_probs"])
    ver, mask = data[FIELD], data["response_mask"]
    lens = mask.offsets().diff()
    vals, m = ver.values().long(), mask.values()
    if vals.numel() != m.numel():
        raise RuntimeError(f"{vals.numel()} token versions for {m.numel()} response tokens")
    return vals, m, lens, data["rollout_log_probs"].values()


def _tag_metrics(batch, cur, vals, m, lens) -> dict:
    tags = [t for t in batch.tags]
    tmin = [t.get("min_global_steps") for t in tags]
    tmax = [t.get("max_global_steps") for t in tags]
    out = tag_token_consistency(tmin, tmax, vals, m, lens)
    hi = [cur - int(x) for x, t in zip(tmax, tags) if x is not None and not t.get("is_padding", False)]
    if hi:
        out["tim/async_tag_gap_mean"] = sum(hi) / len(hi)
        out["tim/async_tag_gap_max"] = float(max(hi))
    return out


def _check_versions(vals, m, cur) -> None:
    v = vals[m.bool()]
    if v.numel() and bool((v < 0).any()):
        raise RuntimeError("valid response tokens without a version (the vLLMHttpServer / client patches of "
                           "tim.dlc.async_hooks did not run in the rollout processes)")
    if v.numel() and int(v.max()) > cur:
        raise RuntimeError(f"token version {int(v.max())} newer than the trainer's {cur}")


def _reissue(trainer, st, uids, tu) -> tuple[list, int]:
    """Submit the prompts of `uids` again under fresh uids through verl's own _submit_batch_to_rollout (TransferQueue
    registration with the current global_steps as tag, then the agent loop); returns ([(new uid, old uid)], number of
    uids without a stored prompt: e.g. prompts re-issued by verl after a resume, which bypass the submit wrapper)."""
    groups, missing = {}, 0
    for uid in uids:
        entry = st.prompts.get(uid)
        if entry is None:
            missing += 1
            continue
        td, row, root, _ = entry
        groups.setdefault(id(td), (td, []))[1].append((row, root, uid))
    pairs = []
    for td, rows in groups.values():
        sel = tu.index_select_tensor_dict(td, [r for r, _, _ in rows])
        new = [str(uuid.uuid4()) for _ in rows]
        tu.assign_non_tensor_stack(sel, "uid", new)
        tu.assign_non_tensor_data(sel, "global_steps", trainer.global_steps)
        for u, (_, root, old) in zip(new, rows):
            st.roots[u] = root           # read by the submit wrapper: the new prompt keeps its original's defer count
            pairs.append((u, old))
        trainer._submit_batch_to_rollout(sel)
    st.roots.clear()
    return pairs, missing


def make_old_log_prob(module_sa, module_tb):
    cls = module_sa.PPOTrainerSeparateAsync
    if "_compute_old_log_prob" not in cls.__dict__:
        raise RuntimeError("PPOTrainerSeparateAsync no longer defines _compute_old_log_prob; re-check the patch target")
    original = cls.__dict__["_compute_old_log_prob"]
    base = module_tb.PPOTrainer
    tq, tu = module_tb.tq, module_tb.tu
    response_from_nested = module_tb.response_from_nested
    mode, engine, keep = old_mode(), _engine(), int(os.environ.get(ENV_KEEP, "5") or 5)
    threshold = ess_min()
    max_defer = int(os.environ.get(ENV_MAX_DEFER, "3") or 3)
    on_missing = os.environ.get(ENV_MISSING, "") or "mask"
    if engine not in ("sc", "none"):
        raise ValueError(f"TIM_SPLIT_ENGINE={engine!r}: sc (DLC) or none (m2po, pg, tis)")
    if threshold is not None and mode != "version":
        raise ValueError(f"{ENV_ESS} needs {ENV_OLD}=version")

    def _compute_old_log_prob(self, batch, metrics):
        from tensordict import TensorDict
        import torch
        if self.parameter_sync_step != 1:
            raise RuntimeError(f"continuous asynchrony needs parameter_sync_step=1 (weights pushed after every step), got "
                               f"{self.parameter_sync_step}")
        st = _state(self)
        cur = int(self.global_steps) - 1
        vals, m, lens, logq = _batch_versions(tq, batch)
        _check_versions(vals, m, cur)
        out = {"tim/async_cur_version": float(cur)}
        out.update(gap_stats(vals, m, lens, cur))
        out.update(_tag_metrics(batch, cur, vals, m, lens))
        if mode == "metrics":
            metrics.update(out)
            STATE[RAN] = self.global_steps
            return original(self, batch, metrics)

        rc = self.config.algorithm.get("rollout_correction", None)
        if rc and rc.get("bypass_mode", False):
            raise RuntimeError(f"{ENV_OLD}=version needs the decoupled mode (rollout_correction.bypass_mode=false)")
        if getattr(base._compute_old_log_prob, "tim_split", None):
            raise RuntimeError("the PPOTrainer._compute_old_log_prob patch of tim.dlc.hooks (TIM_SPLIT_OLD=ref) is armed: "
                               "continuous asynchrony uses TIM_SPLIT_OLD=async")
        t0 = time.time()
        wg = self.actor_rollout_wg
        wg.save_model_to_cpu(cur)
        st.kept.add(cur)
        for v in versions_to_evict(st.kept, cur, keep):
            wg.clear_cpu_model(v)
            st.kept.discard(v)
        valid = m.bool()
        need = sorted(int(v) for v in torch.unique(vals[valid]).tolist())
        missing = [k for k in need if k != cur and k not in st.kept]
        if missing and on_missing == "raise":
            raise RuntimeError(f"versions {missing} in the batch have no CPU snapshot (kept {sorted(st.kept)})")
        sc = engine == "sc"
        per_lp, per_head, restored = {}, {}, False
        # every forward runs on the sampled meta itself (tq.kv_batch_put returns a new KVBatchMeta whose extra_info is
        # not the one carrying the flag); the flag makes the actor engine also return log p at the sampler's head ids
        meta = batch
        if sc:
            meta.extra_info[REF_FLAG] = True
        try:
            base._compute_old_log_prob(self, meta, metrics)     # theta_t: old_log_probs, entropy, debug metrics
            d = tq.kv_batch_get(keys=meta.keys, partition_id=meta.partition_id,
                                select_fields=["old_log_probs"] + ([REF_FIELD] if sc else []))
            lp_t = d["old_log_probs"]
            head_t = d[REF_FIELD] if sc else None
            for k in need:
                if k == cur or k in missing:
                    continue
                wg.restore_model_from_cpu(k)
                restored = True
                meta.extra_info.update({"calculate_entropy": False, "compute_loss": False,
                                        "temperature": self.config.actor_rollout_ref.rollout.temperature})
                if sc:
                    meta.extra_info[REF_FLAG] = True
                wg.compute_log_prob(meta)
                dk = tq.kv_batch_get(keys=meta.keys, partition_id=meta.partition_id,
                                     select_fields=["log_probs", "response_mask"] + ([REF_FIELD] if sc else []))
                per_lp[k] = response_from_nested(dk["log_probs"], dk["response_mask"]).values()
                if sc:
                    per_head[k] = dk[REF_FIELD].values()
        finally:
            if restored:
                wg.restore_model_from_cpu(cur)
            meta.extra_info.pop(REF_FLAG, None)

        lp_t_vals = lp_t.values()
        old = merge_by_version(lp_t_vals, vals, per_lp)
        fields = {"old_log_probs": torch.nested.nested_tensor_from_jagged(old.contiguous(), lp_t.offsets()),
                  STASH: lp_t}
        if sc:
            rows = full_row_versions(head_t.offsets(), lens, vals)
            head = merge_by_version(head_t.values(), rows, per_head)
            fields[REF_FIELD] = torch.nested.nested_tensor_from_jagged(head.contiguous(), head_t.offsets())

        # diagnostics: per-version vs sampler (bf16 noise expected), current vs sampler, the lag ratio
        out.update(abs_diff_by_gap(old, logq, vals, m, cur, "old_minus_q"))
        out.update(abs_diff_by_gap(lp_t_vals, logq, vals, m, cur, "cur_minus_q"))
        from tim.dlc.hooks import lag_metrics
        out.update(lag_metrics(lp_t, fields["old_log_probs"]))
        out["tim/async_versions_forwarded"] = float(len(per_lp))
        out["tim/async_kept_versions"] = float(len(st.kept))

        # responses to drop: a version without snapshot (masked), ESS below the threshold (masked + re-issued)
        n_resp = int(lens.numel())
        idx = torch.repeat_interleave(torch.arange(n_resp), lens)
        tok_missing = torch.zeros_like(valid)
        for k in missing:
            tok_missing |= valid & (vals == k)
        resp_missing = torch.zeros(n_resp, dtype=torch.bool).index_fill_(0, idx[tok_missing].unique(), True) \
            if bool(tok_missing.any()) else torch.zeros(n_resp, dtype=torch.bool)
        resp_valid = torch.zeros(n_resp, dtype=torch.bool)
        if bool(valid.any()):
            resp_valid.index_fill_(0, idx[valid].unique(), True)
        n_valid = max(int(resp_valid.sum()), 1)
        out["tim/async_missing_resp_frac"] = float(resp_missing.sum()) / n_valid
        drop = resp_missing.clone()
        uids = [_uid(k) for k in batch.keys]
        if threshold is not None:
            ess = ess_per_response(lp_t_vals - old, m, lens)
            defer = defer_responses(ess, threshold, resp_valid & ~resp_missing)

            def root_of(u):
                entry = st.prompts.get(u)
                return entry[2] if entry is not None else u

            capped = 0
            for r in torch.nonzero(defer).flatten().tolist():
                if st.defers.get(root_of(uids[r]), 0) >= max_defer:   # deferred often enough: train it as it is
                    defer[r] = False
                    capped += 1
            drop |= defer
            newest = {}                                 # uid -> newest token version among its deferred responses
            for r in torch.nonzero(defer).flatten().tolist():
                newest[uids[r]] = max(newest.get(uids[r], -1), int(vals[(idx == r) & valid].max()))
            defer_uids = sorted(newest)
            for u in defer_uids:
                st.defers[root_of(u)] = st.defers.get(root_of(u), 0) + 1
            pairs, no_source = _reissue(self, st, defer_uids, tu)
            for new_uid, old_uid in pairs:
                st.reissued[new_uid] = (int(self.global_steps), newest[old_uid])
            n_new = len(pairs)
            st.deferred_total += int(defer.sum())
            valid_ess = ess[resp_valid]
            out.update({"tim/async_ess_mean": float(valid_ess.mean()) if valid_ess.numel() else 1.0,
                        "tim/async_ess_min": float(valid_ess.min()) if valid_ess.numel() else 1.0,
                        "tim/async_ess_deferred": float(defer.sum()),
                        "tim/async_ess_defer_frac": float(defer.sum()) / n_valid,
                        "tim/async_ess_deferred_total": float(st.deferred_total),
                        "tim/async_ess_capped": float(capped),
                        "tim/async_ess_reissued_groups": float(n_new),
                        "tim/async_ess_reissue_no_source": float(no_source)})
            # re-issued groups that reached this batch: generated by a newer version than the deferred responses?
            seen, newer = 0, 0
            for u in sorted(set(uids)):
                if u not in st.reissued:
                    continue
                step0, v0 = st.reissued.pop(u)
                rows_u = torch.tensor([i for i, x in enumerate(uids) if x == u])
                sel = valid & torch.isin(idx, rows_u)
                if not bool(sel.any()):
                    continue
                seen += 1
                newer += int(int(vals[sel].min()) > v0)
            out["tim/async_ess_reissue_seen"] = float(seen)
            out["tim/async_ess_reissue_newer"] = float(newer)
            for u in set(uids):                       # trained (or re-issued under a new uid): forget the prompt
                st.prompts.pop(u, None)
            horizon = int(self.global_steps) - 64
            for u in [u for u, e in st.prompts.items() if e[3] < horizon]:
                st.prompts.pop(u, None)
        if bool(drop.any()):
            mk = tq.kv_batch_get(keys=batch.keys, partition_id=batch.partition_id,
                                 select_fields=["response_mask", "loss_mask"])
            new_m = drop_token_mask(m, lens, drop)
            new_l = drop_token_mask(mk["loss_mask"].values(), mk["loss_mask"].offsets().diff(), drop)
            fields["response_mask"] = torch.nested.nested_tensor_from_jagged(new_m.contiguous(),
                                                                             mk["response_mask"].offsets())
            fields["loss_mask"] = torch.nested.nested_tensor_from_jagged(new_l.contiguous(), mk["loss_mask"].offsets())
        batch = tq.kv_batch_put(keys=batch.keys, partition_id=batch.partition_id,
                                fields=TensorDict(fields, batch_size=len(batch.keys)))
        out["tim/async_version_forward_s"] = time.time() - t0
        metrics.update(out)
        if not STATE.get("async_said"):
            STATE["async_said"] = True
            _say(f"first version-aware old-log-prob at step {self.global_steps}: cur {cur}, versions {need}, "
                 f"forwards {sorted(per_lp)}, missing {missing}, engine {engine}, ESS {threshold}")
        STATE[RAN] = self.global_steps
        return batch

    _compute_old_log_prob.tim_async = mode
    return _compute_old_log_prob


def patch_separate_async(module) -> str:
    import importlib
    tb = importlib.import_module("verl.trainer.ppo.v1.trainer_base")
    cls = module.PPOTrainerSeparateAsync
    if getattr(cls.__dict__.get("_compute_old_log_prob"), "tim_async", None):
        return "applied"
    cls._compute_old_log_prob = make_old_log_prob(module, tb)
    return f"applied (PPOTrainerSeparateAsync._compute_old_log_prob, mode {old_mode()}, engine {_engine()}, " \
           f"keep {os.environ.get(ENV_KEEP, '5')}, ESS {ess_min()})"


def patch_base(module) -> str:
    cls = module.PPOTrainer
    update = cls._update_actor
    if getattr(update, "tim_async", None):
        return "applied"

    def _update_actor(self, batch, metrics):
        if STATE.get(RAN) != self.global_steps:
            raise RuntimeError(f"the version-aware old-log-prob of tim.dlc.async_hooks did not run at step "
                               f"{self.global_steps} (trainer {type(self).__name__}; needs "
                               "trainer.v1.trainer_mode=separate_async and the PPOTrainerSeparateAsync patch)")
        return update(self, batch, metrics)

    _update_actor.tim_async = True
    cls._update_actor = _update_actor
    msg = "applied (_update_actor checks the old-log-prob hook ran)"
    if ess_min() is not None:
        submit = cls._submit_batch_to_rollout

        def _submit_batch_to_rollout(self, batch):
            st = _state(self)
            for row, uid in enumerate(list(batch["uid"])):
                uid = str(uid)
                st.prompts[uid] = (batch, row, st.roots.get(uid, uid), int(self.global_steps))
            return submit(self, batch)

        cls._submit_batch_to_rollout = _submit_batch_to_rollout
        msg += "; prompts kept for ESS re-issue"
    return msg


def apply() -> dict:
    if os.environ.get(ENV, "") != "1":
        return {"async": "off"}
    mode = old_mode()
    ess_min()
    when_imported("verl.workers.rollout.vllm_rollout.vllm_async_server", _strict("async_server", patch_server))
    when_imported("verl.workers.rollout.llm_server", _strict("async_client", patch_client))
    when_imported("verl.experimental.agent_loop.agent_loop", _strict("async_output", patch_output))
    when_imported("verl.experimental.separation.engine_workers", _strict("async_worker", patch_worker))
    when_imported("verl.trainer.ppo.v1.trainer_base", _strict("async_base", patch_base))
    when_imported("verl.trainer.ppo.v1.trainer_separate_async", _strict("async_trainer", patch_separate_async))
    return {"async": mode}


try:
    STATE.update(apply())
    if STATE.get("async", "off") != "off":
        _say(f"async armed: old-log-prob {STATE['async']}, engine {_engine()}, keep {os.environ.get(ENV_KEEP, '5')}, "
             f"ESS {ess_min()}, missing {os.environ.get(ENV_MISSING, '') or 'mask'}")
except Exception as _error:  # bad env must stop the run, not silently train a different method
    raise RuntimeError(f"tim.dlc.async_hooks: invalid TIM_ASYNC_* settings: {_error}") from _error
