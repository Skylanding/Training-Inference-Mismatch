"""Deviation of a trained model from its paired on-policy model: KL(pi_run || pi_ref) on the fixed probe prefixes and the
held-out accuracy difference, at the run's saved steps (every 5).

KL is exact over the full vocabulary: both trainers (the run's kernel set, packed in verl's dynamic micro-batches as in
training; tim.measure.heads) see the same micro-batches, and per probe prefix (every response position of the probe set)
KL = sum_v p_run(v) (log p_run(v) - log p_ref(v)), with log-softmax in fp32 over chunks of rows. Reported: the mean over
all prefixes (the deviation of the paper before division by the noise floor), the mean of per-sequence means, quantiles,
and |delta log p| on the next token. Held-out accuracy: the 64 held-out Countdown prompts x 8 samples, T = 1, top_p = 1,
seed 0, prompt + completion <= 512 tokens, generated by the bf16 sampler refit to the checkpoint, for the run and for the
reference at the same step (the reference's results are cached per step).
"""
from __future__ import annotations

import numpy as np

KL_CHUNK_ROWS = 2048


def kl_stats(kl_rows, seq_offsets, next_absdiff) -> dict:
    """Scalar summary of per-prefix KL values (pure numpy)."""
    kl = np.asarray(kl_rows, dtype=np.float64)
    off = np.asarray(seq_offsets)
    per_seq = np.array([kl[off[i]:off[i + 1]].mean() for i in range(len(off) - 1) if off[i + 1] > off[i]])
    q = np.quantile(kl, [0.5, 0.9, 0.99])
    return {"kl_mean": float(kl.mean()), "kl_seq_mean": float(per_seq.mean()), "kl_median": float(q[0]),
            "kl_q90": float(q[1]), "kl_q99": float(q[2]), "kl_max": float(kl.max()),
            "next_abs_dlogp_mean": float(np.mean(next_absdiff)), "n_prefixes": int(kl.size)}


def kl_run_vs_ref(model_run, model_ref, sequences, prompt_len, micro_batch: int = 16, device: str = "cuda") -> tuple:
    """Per response row: KL(p_run || p_ref) over the full vocabulary, and |log p_run(y) - log p_ref(y)| of the next token.
    GPU only. Both models must have the same `_tim_mode` (the same micro-batches are fed to both)."""
    import torch
    from tim.measure.heads import forward_logits, micro_batches, rows_by_sequence
    if getattr(model_run, "_tim_mode", None) != getattr(model_ref, "_tim_mode", None):
        raise ValueError("run and reference trainers must share the forward layout")
    off = rows_by_sequence(prompt_len, [len(s) for s in sequences])
    kl = np.zeros(int(off[-1]), dtype=np.float64)
    nd = np.zeros(int(off[-1]), dtype=np.float64)
    with torch.no_grad():
        for idx in micro_batches(model_run, sequences, micro_batch):
            lr_all = forward_logits(model_run, sequences, idx, device)
            lf_all = forward_logits(model_ref, sequences, idx, device)
            for r, i in enumerate(idx):
                P, L = int(prompt_len[i]), len(sequences[i])
                a, b = lr_all[r][P - 1:L - 1], lf_all[r][P - 1:L - 1]
                y = torch.as_tensor(np.asarray(sequences[i][P:L]), device=device)[:, None]
                out_kl, out_nd = [], []
                for c in range(0, a.shape[0], KL_CHUNK_ROWS):
                    la = torch.log_softmax(a[c:c + KL_CHUNK_ROWS].float(), -1)
                    lb = torch.log_softmax(b[c:c + KL_CHUNK_ROWS].float(), -1)
                    out_kl.append((la.exp() * (la - lb)).sum(-1).double().cpu())
                    yy = y[c:c + KL_CHUNK_ROWS]
                    out_nd.append((la.gather(-1, yy) - lb.gather(-1, yy)).abs().squeeze(-1).double().cpu())
                    del la, lb
                kl[off[i]:off[i + 1]] = torch.cat(out_kl).numpy()
                nd[off[i]:off[i + 1]] = torch.cat(out_nd).numpy()
            del lr_all, lf_all
    return kl, nd, off


def build_prompts(tok, heldout, template):
    """Token ids of each held-out prompt: Qwen3 chat template, enable_thinking=False, generation prompt appended."""
    from tim.tasks.countdown import messages
    prompts = []
    for p in heldout:
        text = tok.apply_chat_template(messages(p), tokenize=False, add_generation_prompt=True,
                                       enable_thinking=False, chat_template=template)
        prompts.append(tok.encode(text, add_special_tokens=False))
    return prompts


def generate(llm, prompts, sampling_params_cls, n_samples, max_total_len, seed, stop_ids):
    """n samples per prompt, T=1, top_p=1, top_k=-1, prompt + completion <= max_total_len, seed + prompt index."""
    params = [sampling_params_cls(n=n_samples, temperature=1.0, top_p=1.0, top_k=-1,
                                  max_tokens=max_total_len - len(ids), seed=seed + i, stop_token_ids=stop_ids)
              for i, ids in enumerate(prompts)]
    return llm.generate([{"prompt_token_ids": ids} for ids in prompts], params, use_tqdm=False)


def score_outputs(heldout, outs):
    """Mean 0/1 reward, mean completion length, fraction with a closed answer tag, fraction truncated."""
    from tim.tasks.countdown import compute_reward, extract_answer
    acc, lens, tagged, trunc, n = 0.0, 0, 0, 0, 0
    for p, o in zip(heldout, outs):
        for c in o.outputs:
            acc += compute_reward(c.text, p["numbers"], p["target"])
            lens += len(c.token_ids)
            tagged += extract_answer(c.text) is not None
            trunc += c.finish_reason == "length"
            n += 1
    return {"n_prompts": len(heldout), "n_completions": n, "mean_accuracy": acc / n, "mean_completion_len": lens / n,
            "frac_answer_tag": tagged / n, "frac_truncated": trunc / n}


def heldout_accuracy(llm, base_model: str, n_prompts: int = 64, n_samples: int = 8, seed: int = 0, cfg: dict = None,
                     max_total_len: int = 512) -> dict:
    """Held-out Countdown accuracy on an engine that already holds the checkpoint's weights (module docstring); the chat
    template is the config's `template` (configs/chat-templates/qwen3.jinja by default)."""
    from vllm import SamplingParams
    from tim.measure.config import ROOT, init_eos_ids
    from tim.tasks.countdown import build_dataset
    import os
    template = (cfg or {}).get("template") or os.path.join(ROOT, "configs", "chat-templates", "qwen3.jinja")
    heldout, _ = build_dataset(n_heldout=n_prompts)
    prompts = build_prompts(llm.get_tokenizer(), heldout, open(template).read())
    outs = generate(llm, prompts, SamplingParams, n_samples, max_total_len, seed, init_eos_ids(base_model))
    return score_outputs(heldout, outs)
