"""Deviation tables from results/deviation_<model> (pure python + numpy).

Run names are <prefix>_<source>_<method>_seed<k> with the internal source and method names of scripts/train.sh
(README.md, "Run names"): sources bf16 (on-policy), fp8 (quantized), stale64 (stale), fp8_stale64, eager, budget (stale with
ESS-triggered resynchronization), async4; methods pg, pg4 (PPO without clip), ppo, tis (importance sampling), sc (score
centering), tis_sc, split (DLC), split_async, split_async_ess, m2po, vcpo.

steps.csv  one row per (run, step): KL(pi_run || pi_ref) on the probe prefixes, held-out accuracy of run and reference
TABLES.md  at each saved step: per source x method, mean over seeds [per seed] of the KL, its excess over the same-seed
           noise floor (KL_run - KL_floor, the floor = the bf16 PG re-run of the reference configuration), the ratio
           KL_run / KL_floor, and the held-out accuracy difference run - reference
"""
from __future__ import annotations

import csv
import json
import re
from pathlib import Path

import numpy as np

RUN = re.compile(r"^(?P<prefix>[a-z0-9]+)_(?P<source>bf16|fp8|eager|fp8_stale\d+|stale\d+|syn\d+|fp8_budget|budget|async\d+)"
                 r"_(?P<method>pg4|pg|tis_sc|tis|sc|split_async_ess|split_async|split|ppo|m2po|vcpo)_seed(?P<seed>\d+)$")
# s9b_async4_* (continuous asynchrony) are measured against s5ref into results/deviation_1.7b


def parse_run(run: str) -> dict:
    m = RUN.match(run)
    if not m:
        raise ValueError(f"not a run name of the form <prefix>_<source>_<method>_seed<k>: {run}")
    d = m.groupdict()
    d["seed"] = int(d["seed"])
    return d


def _fmt(vals, signed=False):
    vals = [v for v in vals if v is not None and np.isfinite(v)]
    if not vals:
        return "n/a"
    f = "{:+.3g}" if signed else "{:.3g}"
    return f.format(np.mean(vals)) + " [" + ", ".join(f.format(v) for v in vals) + "]"


def summarize(root: Path, cfg2: dict, title: str = "Deviation tables, Qwen3-0.6B", command: str = "summarize deviation",
              probe: str = "probe prefixes of theta_0") -> list:
    root = Path(root)
    rows = []
    for f in sorted(root.glob("*/step_*.json")):
        if f.parent.name.startswith("_"):
            continue
        r = json.loads(f.read_text())
        rows.append({"run": r["run"], **parse_run(r["run"]), "step": r["step"], "kl_mean": r["kl"]["kl_mean"],
                     "kl_seq_mean": r["kl"]["kl_seq_mean"], "next_abs_dlogp_mean": r["kl"]["next_abs_dlogp_mean"],
                     "acc_run": r["heldout_run"]["mean_accuracy"], "acc_ref": r["heldout_ref"]["mean_accuracy"],
                     "acc_diff": r["heldout_acc_diff"]})
    rows.sort(key=lambda x: (x["source"], x["method"], x["seed"], x["step"]))
    if rows:
        with open(root / "steps.csv", "w", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=list(rows[0]))
            w.writeheader()
            w.writerows(rows)
    floor_src, floor_m = cfg2["noise_floor_source"], cfg2["noise_floor_method"]
    floor = {(x["seed"], x["step"]): x["kl_mean"] for x in rows if x["source"] == floor_src and x["method"] == floor_m}
    cells = sorted({(x["source"], x["method"]) for x in rows}, key=lambda c: (c != (floor_src, floor_m), c))
    md = [f"# {title}", "", f"Generated by `scripts/measure.py {command}`. KL(pi_run || pi_ref) on the "
          f"{probe} against the same-seed reference; noise floor = the bf16 PG re-runs of the reference "
          "configuration. Mean over seeds, per-seed values in brackets.", ""]
    for step in sorted({x["step"] for x in rows}):
        md += [f"## step {step}", "", "| source | method | KL | KL - floor | KL / floor | held-out acc run - ref |",
               "|---|---|---|---|---|---|"]
        for src, m in cells:
            sel = sorted((x for x in rows if x["source"] == src and x["method"] == m and x["step"] == step),
                         key=lambda x: x["seed"])
            kl = [x["kl_mean"] for x in sel]
            fl = [floor.get((x["seed"], step)) for x in sel]
            ex = [k - f if f is not None else None for k, f in zip(kl, fl)]
            ra = [k / f if f else None for k, f in zip(kl, fl)]
            md.append(f"| {src} | {m} | {_fmt(kl)} | {_fmt(ex, True)} | {_fmt(ra)} | "
                      f"{_fmt([x['acc_diff'] for x in sel], True)} |")
        md.append("")
    (root / "TABLES.md").write_text("\n".join(md) + "\n")
    return [f"{len(rows)} step results -> {root}/steps.csv, TABLES.md"]
