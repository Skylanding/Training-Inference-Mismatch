"""summarize loop: results/loop_<model>/<run>/step_<t>.json -> TABLES.md (pure python, as tim.measure.split.summary);
summarize residual-bias-exact: results/residual_bias_exact_0.6b/<run>/step_<t>.json -> TABLES.md and steps.csv.

Groups are (model, source, method) over seeds 0-2; each cell is the seed mean with the per-seed values in brackets.
6a-1: cos(b_pred, b) against the noise floor cos(b_pred_total, n), |b_pred| / |b|, cos(b_pred, Delta_cum), the Abar subset.
6a-2: the lag split by sign of A and of A - Abar, and the largest-|l| tokens.
"""
from __future__ import annotations

import json
from pathlib import Path

from tim.measure.split.summary import _fmt


def load(root: Path) -> list:
    return [json.loads(f.read_text()) for f in sorted(root.glob("s*_*/step_*.json"))]


def _get(r: dict, path: str):
    # "/" separates keys; "." too unless the path has a "/" (the top-token fractions are keys like "0.01")
    for k in (path.split("/") if "/" in path else path.split(".")):
        if not isinstance(r, dict) or k not in r:
            return None
        r = r[k]
    return r


def summarize(root: Path, c6: dict) -> list:
    rows = load(root)
    if not rows:
        return [f"no loop results under {root}"]
    steps = c6["steps"]
    for r in rows:
        r["model"] = r["run"].split("_")[0]
    groups = sorted({(r["model"], r["source"], r["method"]) for r in rows})
    by = {(r["model"], r["source"], r["method"], r["seed"], r["step"]): r for r in rows}
    seeds = sorted({r["seed"] for r in rows})

    def cell(g, t, path):
        return [_get(by.get((*g, s, t), {}), path) for s in seeds]

    def table(g, cols, fmt="{:.3g}"):
        L = ["| t | " + " | ".join(h for h, _ in cols) + " |", "|---" * (len(cols) + 1) + "|"]
        for t in steps:
            cs = [cell(g, t, p) for _, p in cols]
            if all(x is None for c in cs for x in c):
                continue
            L.append(f"| {t} | " + " | ".join(_fmt(c, fmt) for c in cs) + " |")
        return L + [""]

    L = ["# Loop tables", "",
         f"Generated by `scripts/measure.py summarize loop` from `results/{root.name}/<run>/step_<t>.json`. Cells: "
         f"mean over seeds, per-seed values in brackets (seeds {seeds}). l = log p_theta_t(y) - log p_theta_0(y) (trainer numerics), "
         "b = g_corr - g_on, n = g_on' - g_on, Delta_cum = theta_t - theta_0; b_pred = -grad sum_t w_t log p(y_t) / N with w = A l "
         "(SC token term) and A sum_{t'<t} l (prefix term; TIS: prefix only).", ""]
    for g in groups:
        name = " ".join(g)
        if any(_get(r, "6a1") for r in rows if (r["model"], r["source"], r["method"]) == g):
            L += [f"## 6a-1 {name}", ""]
            cols = []
            for x in ("token", "prefix", "total"):
                if any(_get(r, f"6a1.pred.{x}") for r in rows if (r["model"], r["source"], r["method"]) == g):
                    cols += [(f"cos(b_pred_{x}, b)", f"6a1.pred.{x}.cos_b"), (f"\\|{x}\\| / \\|b\\|", f"6a1.pred.{x}.ratio"),
                             (f"cos({x}, Delta)", f"6a1.pred.{x}.cos_delta")]
            cols += [("cos(total, n) (floor)", "6a1.pred.total.cos_noise"), ("\\|b\\|", "6a1.pred.b_norm"),
                     ("\\|n\\|", "6a1.pred.noise_norm"), ("\\|Delta\\|", "6a1.pred.delta_cum_norm"),
                     ("mean l", "6a1.lag.mean"), ("mean \\|l\\|", "6a1.lag.abs_mean")]
            L += table(g, cols)
            if g[2] == "sc":
                L += [f"### 6a-1 {name}: 512-position subset, SC token term with A and with A - Abar", ""]
                L += table(g, [("mean\\|Abar\\|/mean\\|A\\|", "6a1.subset.abar_ratio"), ("cos(sub_A, b)", "6a1.subset.sub_A.cos_b"),
                               ("cos(sub_A-Abar, b)", "6a1.subset.sub_Abar.cos_b"), ("cos(sub_A, sub_A-Abar)", "6a1.subset.cos_sub_A_vs_Abar"),
                               ("\\|sub_A\\|/\\|b\\|", "6a1.subset.sub_A.ratio"), ("\\|sub_A-Abar\\|/\\|b\\|", "6a1.subset.sub_Abar.ratio")])
            else:
                L += [f"mean\\|Abar\\|/mean\\|A\\| on the subset ({name}):", ""]
                L += table(g, [("ratio", "6a1.subset.abar_ratio")])
        L += [f"## 6a-2 {name}: lag by group (share = share of sum(l); mean/|Delta|^2 = |mean l| / |Delta_cum|^2)", ""]
        cols = [("mean l", "6a2.lag_mean"), ("\\|Delta\\|^2", "6a2.delta_cum_sq")]
        for grp in ("neg", "pos"):
            cols += [(f"A{'<' if grp == 'neg' else '>'}0 mean l", f"6a2.by_A.{grp}.mean"), ("share", f"6a2.by_A.{grp}.share_sum"),
                     ("\\|mean\\|/\\|D\\|^2", f"6a2.by_A.{grp}.abs_mean_over_delta_sq")]
        L += table(g, cols, "{:+.4g}")
        L += [f"### 6a-2 {name}: 512 positions by sign of A - Abar", ""]
        cols = [("mean\\|Abar\\|/mean\\|A\\|", "6a2.subset.abar_ratio")]
        for grp in ("neg", "pos"):
            cols += [(f"A-Abar{'<' if grp == 'neg' else '>'}0 mean l", f"6a2.subset.by_A_minus_Abar.{grp}.mean"),
                     ("share", f"6a2.subset.by_A_minus_Abar.{grp}.share_sum"),
                     ("\\|mean\\|/\\|D\\|^2", f"6a2.subset.by_A_minus_Abar.{grp}.abs_mean_over_delta_sq")]
        L += table(g, cols, "{:+.4g}")
        for f in ("0.01", "0.001"):
            L += [f"### 6a-2 {name}: top {float(f):.1%} tokens by \\|l\\|", ""]
            L += table(g, [("share of sum(l)", f"6a2/top/{f}/share_sum"), ("p_t < 1e-3", f"6a2/top/{f}/frac_p_below"),
                           ("A<0", f"6a2/top/{f}/frac_adv_neg"), ("A>0", f"6a2/top/{f}/frac_adv_pos"),
                           ("A=0", f"6a2/top/{f}/frac_adv_zero"), ("pos mean", f"6a2/top/{f}/pos_mean"),
                           ("rel pos mean", f"6a2/top/{f}/rel_pos_mean")])
    (root / "TABLES.md").write_text("\n".join(L) + "\n")
    return [f"{len(rows)} step results -> {root / 'TABLES.md'}"]


# ------------------------------------------------------------------------------------- exact-weight residual bias
EXACT_COLS = ("cos_b", "ratio", "cos_noise", "cos_delta", "norm")


def flat_exact(r: dict) -> dict:
    """One CSV row of an exact-weight step: <version>_<term>_<scalar> for version lin / exact, term token / prefix / total (and the SC
    subset terms), plus |b|, |n|, |Delta| and the exact-weight diagnostics."""
    out = {k: r[k] for k in ("run", "source", "method", "seed", "step")}
    for v in ("lin", "exact"):
        pr = _get(r, f"{v}/pred") or {}
        for term in ("token", "prefix", "total"):
            for s in EXACT_COLS:
                out[f"{v}_{term}_{s}"] = _get(pr, f"{term}/{s}")
        for term in ("sub_A", "sub_Abar"):
            for s in ("cos_b", "ratio"):
                out[f"{v}_{term}_{s}"] = _get(r, f"{v}/subset/{term}/{s}")
        out[f"{v}_cos_token_prefix"] = _get(r, f"{v}/cos_token_prefix")
    for k in ("b_norm", "noise_norm", "delta_cum_norm"):
        out[k] = _get(r, f"lin/pred/{k}")
    d = r.get("diag", {})
    for k in ("lag_mean", "delta_mean", "engine_mean", "abar_ratio", "n_tokens"):
        out[k] = d.get(k)
    e = d.get("exact", {})
    out.update(abs_S_max=e.get("abs_S_max"), S_max=e.get("S_max"), frac_abs_S_gt_1=e.get("frac_abs_S_gt_1"),
               frac_ratio_gt_cap=e.get("frac_ratio_gt_cap"), mean_one_minus_exp_S=e.get("mean_one_minus_exp_S"),
               n_clipped=e.get("n_clipped"))
    return out


def summarize_exact(root: Path, steps: list) -> list:
    """results/residual_bias_exact_0.6b/<run>/step_<t>.json -> TABLES.md and steps.csv: per (source, method), over t, the linearised and the
    exact version side by side (cos(b_pred, b), |b_pred| / |b|) for the token, prefix and total terms."""
    import csv
    rows = load(root)
    if not rows:
        return [f"no exact-weight results under {root}"]
    flat = [flat_exact(r) for r in rows]
    cols = list(dict.fromkeys(k for f in flat for k in f))
    with open(root / "steps.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        w.writerows(sorted(flat, key=lambda x: (x["run"], x["step"])))
    groups = sorted({(r["source"], r["method"]) for r in rows})
    by = {(r["source"], r["method"], r["seed"], r["step"]): r for r in rows}
    seeds = sorted({r["seed"] for r in rows})

    def table(g, cols, fmt="{:.3g}"):
        L = ["| t | " + " | ".join(h for h, _ in cols) + " |", "|---" * (len(cols) + 1) + "|"]
        for t in steps:
            cs = [[_get(by.get((*g, s, t), {}), p) for s in seeds] for _, p in cols]
            if all(x is None for c in cs for x in c):
                continue
            L.append(f"| {t} | " + " | ".join(_fmt(c, fmt) for c in cs) + " |")
        return L + [""]

    L = ["# Residual bias: linearised vs exact weights", "",
         f"Generated by `scripts/measure.py summarize residual-bias-exact` from `results/{root.name}/<run>/step_<t>.json`. "
         f"Cells: mean over seeds, per-seed values in brackets (seeds {seeds}). Both versions on the same regenerated 4a batch "
         "against the same b = g_corr - g_on and n = g_on' - g_on. lin: w = -A l (SC token), -A sum_{t'<t} l (prefix); exact: "
         "A (1 - e^{delta}) (SC token), -A max(e^{delta} - 2, 0) (TIS token), A (1 - e^{S_t}) (prefix), S_t = sum_{t'<t} delta; "
         "delta = l on stale64, log p_theta_t - log q on fp8_stale64.", ""]
    for g in groups:
        name = " ".join(g)
        L += [f"## {name}: cos(b_pred, b) and \\|b_pred\\| / \\|b\\|", ""]
        cols = []
        for term in ("token", "prefix", "total"):
            for s, h in (("cos_b", "cos"), ("ratio", "ratio")):
                for v in ("lin", "exact"):
                    if g[1] == "tis" and term == "token" and v == "lin":
                        continue                         # the linearised TIS weights have no token term
                    cols.append((f"{term} {h} {v}", f"{v}/pred/{term}/{s}"))
        L += table(g, cols)
        L += [f"### {name}: noise floor cos(b_pred_total, n), cos(b_pred, Delta_cum), cos(token, prefix)", ""]
        L += table(g, [("floor lin", "lin/pred/total/cos_noise"), ("floor exact", "exact/pred/total/cos_noise"),
                       ("cos(total, Delta) lin", "lin/pred/total/cos_delta"), ("cos(total, Delta) exact", "exact/pred/total/cos_delta"),
                       ("cos(tok, pre) lin", "lin/cos_token_prefix"), ("cos(tok, pre) exact", "exact/cos_token_prefix"),
                       ("\\|b\\|", "lin/pred/b_norm"), ("\\|n\\|", "lin/pred/noise_norm")])
        if g[1] == "sc":
            L += [f"### {name}: 512-position subset, SC token term with A and A - Abar", ""]
            L += table(g, [(f"cos(sub_{a}, b) {v}", f"{v}/subset/sub_{a}/cos_b") for a in ("A", "Abar") for v in ("lin", "exact")]
                       + [(f"ratio sub_{a} {v}", f"{v}/subset/sub_{a}/ratio") for a in ("A", "Abar") for v in ("lin", "exact")]
                       + [("mean\\|Abar\\|/mean\\|A\\|", "diag/abar_ratio")])
        L += [f"### {name}: how far from linear (delta = the exponent's source)", ""]
        L += table(g, [("mean delta", "diag/delta_mean"), ("mean l", "diag/lag_mean"), ("max \\|S\\|", "diag/exact/abs_S_max"),
                       ("max S", "diag/exact/S_max"), ("\\|S\\|>1", "diag/exact/frac_abs_S_gt_1"),
                       ("e^delta>2", "diag/exact/frac_ratio_gt_cap"), ("mean(1-e^S)", "diag/exact/mean_one_minus_exp_S"),
                       ("clipped", "diag/exact/n_clipped")], "{:+.4g}")
    (root / "TABLES.md").write_text("\n".join(L) + "\n")
    return [f"{len(rows)} step results -> {root / 'TABLES.md'}, {root / 'steps.csv'}"]
