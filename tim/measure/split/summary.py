"""summarize split: results/split_<model>/<run>/step_<t>.json -> TABLES.md and steps.csv in the same directory (pure python).

Groups are (source, method) over seeds 0-2; each table cell is the seed mean with the per-seed values in brackets.
4a: |b| and the noise floor |n| per step, the ratio |b| / |n|, cos(b, dtheta_recent) and cos(b, dtheta_cum) beside the
noise's; the slope of |b| over t; a quantity counts as present when it exceeds 2 x its noise floor.
4b (TIS runs): projections of the TIS and SC gradients and of their p/q < 0.5 parts on dtheta; the token statistics.
4c: mean delta and its lag / engine parts per step; the first step from which each class separates from the eager runs.
"""
from __future__ import annotations

import csv
import json
import math
from pathlib import Path

import numpy as np

from tim.measure.split import pure


def load(root: Path, run_glob: str = "s2_*") -> list:
    rows = []
    for f in sorted(root.glob(f"{run_glob}/step_*.json")):
        rows.append(json.loads(f.read_text()))
    return rows


def _fmt(vals, f="{:.3g}"):
    v = [x for x in vals if x is not None and np.isfinite(x)]
    if not v:
        return "n/a"
    return f.format(float(np.mean(v))) + " [" + ", ".join(f.format(x) if x is not None else "-" for x in vals) + "]"


def _flat(r: dict) -> dict:
    a, c = r["4a"], r["4c"]
    out = {"run": r["run"], "source": r["source"], "method": r["method"], "seed": r["seed"], "step": r["step"],
           **{f"4a_{k}": v for k, v in a.items()}, **{f"4c_{k}": v for k, v in c.items() if not isinstance(v, list)},
           "b_over_noise": a["b_norm"] / a["noise_norm"] if a["noise_norm"] > 0 else float("nan")}
    if "4b" in r:
        out.update({f"4b_proj_{k}": v for k, v in r["4b"]["proj"].items()})
        out.update({f"4b_{k}": v for k, v in r["4b"]["tokens"].items() if not isinstance(v, list)})
    return out


def summarize(root: Path, cfg4: dict, title: str = "Split and residual bias tables, Qwen3-0.6B",
              command: str = "summarize split", note: str = "offline split and residual bias") -> list:
    """cfg4 keys used besides steps: run_glob (default s2_*), floor_source_4c (default eager: the transient class 4c
    separates from; Qwen3-1.7B has no eager runs and uses its bf16 noise-floor runs)."""
    rows = [_flat(r) for r in load(root, cfg4.get("run_glob", "s2_*"))]
    if not rows:
        return [f"no split results under {root}"]
    keys = sorted({k for r in rows for k in r})
    with open(root / "steps.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=keys)
        w.writeheader()
        for r in sorted(rows, key=lambda r: (r["source"], r["method"], r["seed"], r["step"])):
            w.writerow(r)
    steps = cfg4["steps"]
    groups = sorted({(r["source"], r["method"]) for r in rows})
    by = {(r["source"], r["method"], r["seed"], r["step"]): r for r in rows}
    seeds = sorted({r["seed"] for r in rows})

    def series(g, key):
        return [[by.get((g[0], g[1], s, t), {}).get(key) for s in seeds] for t in steps]

    L = [f"# {title}", "",
         f"Generated by `scripts/measure.py {command}` from `results/{root.name}/<run>/step_<t>.json` ({note}). Cells: mean over seeds, per-seed values in brackets "
         f"(seeds {seeds}). Gradients: ascent direction, token-mean, at theta_t; b = g_corr - g_on, n = g_on' - g_on "
         "(sampling noise floor); dtheta_recent = theta_t - theta_(t-5), dtheta_cum = theta_t - theta_0.", ""]
    L += ["## 4a remaining gradient bias", ""]
    for g in groups:
        L += [f"### {g[0]} {g[1]}", "", "| t | \\|b\\| | \\|n\\| (floor) | \\|b\\| / \\|n\\| | cos(b, recent) | cos(n, recent) | "
              "cos(b, cum) | cos(n, cum) |", "|---|---|---|---|---|---|---|---|"]
        for i, t in enumerate(steps):
            cols = [series(g, k)[i] for k in ("4a_b_norm", "4a_noise_norm", "b_over_noise", "4a_b_cos_recent",
                                               "4a_noise_cos_recent", "4a_b_cos_cum", "4a_noise_cos_cum")]
            if all(x is None for c in cols for x in c):
                continue
            L.append(f"| {t} | " + " | ".join(_fmt(c) for c in cols) + " |")
        bn = [np.nanmean([x for x in row if x is not None]) if any(x is not None for x in row) else float("nan")
              for row in series(g, "4a_b_norm")]
        L += ["", f"slope of mean |b| over t: {pure.linear_slope(steps, bn):.3g} per step", ""]
    tis = [g for g in groups if g[1] == "tis"]
    if tis:
        L += ["## 4b TIS runs: projections on dtheta_recent (<g, d>/|d|) and down-weighted tokens", "",
              "| source | t | TIS | SC (same data) | TIS, p/q < 0.5 | SC, p/q < 0.5 | share p/q < 0.5 | share p/q > 2 | mean delta |",
              "|---|---|---|---|---|---|---|---|---|"]
        for g in tis:
            for i, t in enumerate(steps):
                cols = [series(g, k)[i] for k in ("4b_proj_tis:recent", "4b_proj_sc:recent", "4b_proj_tis_low:recent",
                                                   "4b_proj_sc_low:recent", "4b_frac_low", "4b_frac_truncated",
                                                   "4b_delta_mean")]
                if all(x is None for c in cols for x in c):
                    continue
                L.append(f"| {g[0]} | {t} | " + " | ".join(_fmt(c) for c in cols) + " |")
        L.append("")
    L += ["## 4c delta per token and its split (lag = log p_theta - log p_theta_old, engine = log p_theta_old - log q)", "",
          "| source, method | t | delta | lag | engine |", "|---|---|---|---|---|"]
    for g in groups:
        for i, t in enumerate(steps):
            cols = [series(g, k)[i] for k in ("4c_delta_mean", "4c_lag_mean", "4c_engine_mean")]
            if all(x is None for c in cols for x in c):
                continue
            L.append(f"| {g[0]} {g[1]} | {t} | " + " | ".join(_fmt(c, "{:+.4f}") for c in cols) + " |")
    floor_src = cfg4.get("floor_source_4c", "eager")
    floor_g = next((g for g in groups if g[0] == floor_src), None)
    if floor_g:
        L += ["", f"First step from which a class separates from the {floor_src} runs (|value - {floor_src}| > 2 x |{floor_src}| at that "
              "step and every later one; seed means):", ""]
        mean_of = lambda g, k: [float(np.nanmean([x for x in row if x is not None])) if any(x is not None for x in row)
                                else float("nan") for row in series(g, k)]
        for k in ("4c_delta_mean", "4c_lag_mean", "4c_engine_mean"):
            vals = {f"{g[0]} {g[1]}": mean_of(g, k) for g in groups if g != floor_g}
            sep = pure.first_separated(steps, vals, mean_of(floor_g, k))
            L.append(f"- {k[3:]}: " + ", ".join(f"{c} -> {v}" for c, v in sep.items()))
    (root / "TABLES.md").write_text("\n".join(L) + "\n")
    return [f"{len(rows)} step results -> {root / 'steps.csv'}, {root / 'TABLES.md'}"]
