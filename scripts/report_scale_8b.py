#!/usr/bin/env python3
"""Step-40 table of the corrections under the stale sampler on Qwen3-0.6B / 1.7B / 8B (one seed per model; the Qwen3-8B
column is the paper's 8B table): deviation in noise-floor units and held-out accuracy per correction. CPU, reads results/.

    python3 scripts/report_scale_8b.py > results/scale_8b/TABLES.md

Deviation: KL(run || same-seed on-policy reference) on the probe prefixes at step 40 (results/deviation_0.6b,
deviation_1.7b, deviation_8b), divided by the same KL of the noise-floor run (the reference configuration re-run,
s2_bf16_pg_seed0 / s5_bf16_pg_seed0 / s8b_bf16_pg_seed0). Accuracy: the held-out accuracy of the off-support records at
step 40 (results/off_support, 64 x 8) when the run has one, else the deviation record's held-out accuracy (marked *).
Corrections without a run print "-". Internal run names: README.md, "Run names".
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"
STEP = 40
MODELS = {
    "Qwen3-0.6B": {"dev": "deviation_0.6b", "floor": "s2_bf16_pg_seed0", "ref": "s2ref_bf16_pg_seed0", "theta0": "theta0_06b",
                   "rows": {"Policy gradient": "s2_stale64_pg_seed0", "PPO": "s2_stale64_ppo_seed0",
                            "Score centering": "s2_stale64_sc_seed0", "Importance sampling": "s2_stale64_tis_seed0",
                            "Importance sampling with centering": "s2_stale64_tis_sc_seed0",
                            "Importance sampling with resynchronization": "s8a_budget_tis_seed0",
                            "DLC": "s8a_budget_split_seed0",
                            "M2PO": "s8a6_stale64_m2po_seed0", "VCPO": "s8a6_stale64_vcpo_seed0"}},
    "Qwen3-1.7B": {"dev": "deviation_1.7b", "floor": "s5_bf16_pg_seed0", "ref": "s5ref_bf16_pg_seed0", "theta0": "theta0_17b",
                   "rows": {"Policy gradient": "s8a_stale64_pg_seed0", "PPO": "s8a_stale64_ppo_seed0",
                            "Score centering": "s5_stale64_sc_seed0", "Importance sampling": "s5_stale64_tis_seed0",
                            "Importance sampling with centering": "s8a_stale64_tis_sc_seed0",
                            "Importance sampling with resynchronization": "s6c_budget_tis_seed0",
                            "DLC": "s7d_budget_split_seed0",
                            "M2PO": "s8a_stale64_m2po_seed0", "VCPO": "s8a_stale64_vcpo_seed0"}},
    "Qwen3-8B": {"dev": "deviation_8b", "floor": "s8b_bf16_pg_seed0", "ref": "s8ref_bf16_pg_seed0", "theta0": "theta0_8b",
                 "rows": {"Policy gradient": "s8b_stale64_pg_seed0", "PPO": "s8b_stale64_ppo_seed0",
                          "Score centering": "s8b_stale64_sc_seed0", "Importance sampling": "s8b_stale64_tis_seed0",
                          "Importance sampling with centering": "s8b_stale64_tis_sc_seed0",
                          "Importance sampling with resynchronization": "s8b_budget_tis_seed0",
                          "DLC": "s8b_budget_split_seed0",
                          "M2PO": "s8b_stale64_m2po_seed0", "VCPO": "s8b_stale64_vcpo_seed0"}},
}


def load(path: Path):
    return json.loads(path.read_text()) if path.exists() else None


def kl(dev: str, run: str, step: int = STEP):
    r = load(R / dev / run / f"step_{step}.json")
    return r["kl"]["kl_mean"] if r else None


def acc(dev: str, run: str, step: int = STEP):
    r = load(R / "off_support" / run / f"step_{step}.json")
    if r:
        return r["heldout"]["mean_accuracy"], ""
    r = load(R / dev / run / f"step_{step}.json")
    return (r["heldout_run"]["mean_accuracy"], "*") if r else (None, "")


def fmt(x, nd=2, pct=False):
    return "-" if x is None else (f"{100 * x:.1f}" if pct else f"{x:.{nd}f}")


def main():
    names = list(MODELS)
    print("# Corrections under the stale sampler at step 40 (seed 0)\n")
    print("Generated by `scripts/report_scale_8b.py`. Deviation = KL(run || same-seed on-policy reference) on the probe "
          "prefixes divided by the same KL of the noise-floor run; accuracy = held-out accuracy (64 x 8, %) of the "
          "off-support records, * = from the deviation record. Source runs: `MODELS` in the script.\n")
    print("| Correction | " + " | ".join(f"{n} deviation (x floor) | {n} accuracy" for n in names) + " |")
    print("|---|" + "---|---|" * len(names))
    cells = []
    for n in names:
        a0, _ = acc(MODELS[n]["dev"], MODELS[n]["theta0"], 0)
        cells.append(("-", fmt(a0, pct=True)))
    print("| Initial model theta_0 | " + " | ".join(f"{a} | {b}" for a, b in cells) + " |")
    cells = []
    for n in names:
        a, mark = acc(MODELS[n]["dev"], MODELS[n]["ref"])
        cells.append(("1 (reference)", fmt(a, pct=True) + mark))
    print("| On-policy training | " + " | ".join(f"{a} | {b}" for a, b in cells) + " |")
    for method in MODELS[names[0]]["rows"]:
        cells = []
        for n in names:
            m = MODELS[n]
            run = m["rows"][method]
            k, f = kl(m["dev"], run), kl(m["dev"], m["floor"])
            a, mark = acc(m["dev"], run)
            cells.append((fmt(k / f if k is not None and f else None), fmt(a, pct=True) + (mark if a is not None else "")))
        print(f"| {method} | " + " | ".join(f"{a} | {b}" for a, b in cells) + " |")
    print("\nNoise-floor KL at step 40: " + ", ".join(f"{n} {fmt(kl(MODELS[n]['dev'], MODELS[n]['floor']), 4)}" for n in names))


if __name__ == "__main__":
    main()
