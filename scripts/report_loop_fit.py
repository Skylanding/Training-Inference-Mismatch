#!/usr/bin/env python3
"""Residual bias against the accumulated update on the Qwen3-0.6B split records (results/split_0.6b/<run>/step_<t>.json),
pure python: the residual-bias link of the loop, ||b|| linear in ||Delta||.

Per run: x = ||theta_t - theta_old|| with theta_old = theta_0 (stale and quantized-and-stale; for the quantized and eager
runs the same quantity as the control), from the record's 4a.delta_cum_norm. Fits y = a + s x by least squares over
t = 5..40 for
  y1 = ||b||                               (4a.b_norm)
  y2 = <b, dtheta>/||dtheta|| = ||b|| cos  (4a.b_norm * 4a.b_cos_cum)
and the same for the sampling noise n (4a.noise_norm, noise_norm * noise_cos_cum) as the noise floor of the slopes.
Reports slope, intercept, R^2 per seed and the seed mean of each; writes results/loop_fit_0.6b/FIT.md and fit.csv.

    python3 scripts/report_loop_fit.py
"""
import csv, json, math, os, sys
from pathlib import Path
from statistics import mean

ROOT = Path(__file__).resolve().parent.parent
R4 = ROOT / "results" / "split_0.6b"
OUT = ROOT / "results" / "loop_fit_0.6b"


def fit(x, y):
    n = len(x); mx, my = mean(x), mean(y)
    sxx = sum((a - mx) ** 2 for a in x); sxy = sum((a - mx) * (b - my) for a, b in zip(x, y))
    s = sxy / sxx if sxx else float("nan"); a = my - s * mx
    ss_res = sum((b - (a + s * c)) ** 2 for c, b in zip(x, y)); ss_tot = sum((b - my) ** 2 for b in y)
    return s, a, (1 - ss_res / ss_tot) if ss_tot else float("nan")


def main():
    rows = []
    for d in sorted(R4.iterdir()):
        if not d.name.startswith("s2_"):
            continue
        recs = sorted((json.loads(p.read_text()) for p in d.glob("step_*.json")), key=lambda r: r["step"])
        if len(recs) < 3:
            continue
        x = [r["4a"]["delta_cum_norm"] for r in recs]
        series = {"|b|": [r["4a"]["b_norm"] for r in recs],
                  "proj b": [r["4a"]["b_norm"] * r["4a"]["b_cos_cum"] for r in recs],
                  "|n|": [r["4a"]["noise_norm"] for r in recs],
                  "proj n": [r["4a"]["noise_norm"] * r["4a"]["noise_cos_cum"] for r in recs]}
        r0 = recs[0]
        for k, y in series.items():
            s, a, r2 = fit(x, y)
            rows.append({"run": d.name, "source": r0["source"], "method": r0["method"], "seed": r0["seed"], "y": k,
                         "slope": s, "intercept": a, "r2": r2, "x_min": min(x), "x_max": max(x), "n": len(x)})
    if not rows:
        raise SystemExit(f"no split records under {R4} (run scripts/measure.py split first); nothing written")
    OUT.mkdir(parents=True, exist_ok=True)
    with open(OUT / "fit.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)
    groups = {}
    for r in rows:
        groups.setdefault((r["source"], r["method"], r["y"]), []).append(r)
    fmt = lambda v: f"{v:.3g}"
    lines = ["# Residual bias b against ||theta_t - theta_old||", "",
             "Generated by `scripts/report_loop_fit.py` from `results/split_0.6b`. x = ||theta_t - theta_0|| (theta_old = theta_0 for the stale "
             "sources; the same quantity for fp8 and eager as the control), t = 5..40. y: ||b||, the projection of b on "
             "theta_t - theta_0, and the same two for the sampling noise n = g_on' - g_on (the noise floor of a slope). "
             "Mean over seeds, per seed in brackets.", "",
             "| source | method | y | slope | intercept | R^2 | x range |", "|---|---|---|---|---|---|---|"]
    order = ["stale64", "fp8_stale64", "fp8", "eager"]
    for (src, m, y), g in sorted(groups.items(), key=lambda kv: (order.index(kv[0][0]), kv[0][1], kv[0][2])):
        g = sorted(g, key=lambda r: r["seed"])
        cell = lambda k: f"{fmt(mean(r[k] for r in g))} [{', '.join(fmt(r[k]) for r in g)}]"
        lines.append(f"| {src} | {m} | {y} | {cell('slope')} | {cell('intercept')} | {cell('r2')} | "
                     f"{fmt(min(r['x_min'] for r in g))}-{fmt(max(r['x_max'] for r in g))} |")
    (OUT / "FIT.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
